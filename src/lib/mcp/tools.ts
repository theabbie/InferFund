export async function toolContinueAttempt(
  ctx: ToolContext,
  input: z.infer<typeof continueAttemptInput>,
) {
  const actor = requireAuth(ctx);
  requireScope(ctx, "inferfund:contribute");
  const serviceCtx = buildServiceContext(ctx);
  const parent = await findAttemptById(serviceCtx, input.parent_attempt_id);
  if (!parent) {
    throw new InferFundError(
      "ATTEMPT_NOT_FOUND",
      `Parent attempt ${input.parent_attempt_id} does not exist.`,
    );
  }
  if (parent.status !== "merged") {
    throw new InferFundError(
      "INVALID_INPUT",
      "Only merged attempts can be continued.",
    );
  }
  const problem = await getCatalogProblem(parent.problemKey);
  if (!problem) {
    throw new InferFundError(
      "PROBLEM_NOT_FOUND",
      `Problem "${parent.problemKey}" is no longer in the catalog.`,
    );
  }
  const versionId = problemVersionId(
    problem.problemKey,
    problem.upstreamCommit,
    problem.statementHash,
  );
  const result = await createAttempt(serviceCtx, actor, {
    problem,
    problemVersionId: versionId,
    kind: input.kind,
    title: input.title,
    summary: input.summary,
    parents: [
      {
        attempt_id: input.parent_attempt_id,
        relationship: input.relationship as ParentRelationship,
      },
    ],
    idempotencyKey: input.idempotency_key,
  });
  return jsonResult(
    trusted({
      ...result,
      parent: {
        attempt_id: parent.attemptId,
        title: parent.title,
        relationship: input.relationship,
      },
      next_steps:
        "The new attempt is based on the CURRENT progress head; the parent " +
        "attempt directory is untouched. Add new material with update_attempt.",
    }),
  );
}

export async function toolReviewAttempt(
  ctx: ToolContext,
  input: z.infer<typeof reviewAttemptInput>,
) {
  const actor = requireAuth(ctx);
  requireScope(ctx, "inferfund:contribute");
  const negative = new Set([
    "cannot_reproduce",
    "identifies_gap",
    "incorrect",
    "irrelevant",
    "refutes",
  ]);
  if (negative.has(input.review_type) && input.body.trim().length < 50) {
    throw new InferFundError(
      "INVALID_INPUT",
      "Negative reviews require substantive text (at least 50 characters) " +
        "identifying the exact problem.",
    );
  }
  const serviceCtx = buildServiceContext(ctx);
  const target = await findAttemptById(serviceCtx, input.target_attempt_id);
  if (!target) {
    throw new InferFundError(
      "ATTEMPT_NOT_FOUND",
      `Target attempt ${input.target_attempt_id} does not exist.`,
    );
  }
  const relationshipMap: Record<string, ParentRelationship> = {
    supports: "extends",
    reproduces: "reproduces",
    cannot_reproduce: "critiques",
    identifies_gap: "critiques",
    incorrect: "refutes",
    irrelevant: "critiques",
    formalizes: "formalizes",
    refutes: "refutes",
  };
  const problem = await getCatalogProblem(target.problemKey);
  if (!problem) {
    throw new InferFundError(
      "PROBLEM_NOT_FOUND",
      `Problem "${target.problemKey}" is no longer in the catalog.`,
    );
  }
  const created = await createAttempt(serviceCtx, actor, {
    problem,
    problemVersionId: target.manifest.problem.problem_version_id,
    kind: input.review_type === "reproduces" ? "reproduction" : "review",
    title: `Review (${input.review_type}) of ${target.attemptId.slice(0, 8)}`,
    summary: input.body.slice(0, 4000),
    parents: [
      {
        attempt_id: input.target_attempt_id,
        relationship: relationshipMap[input.review_type] ?? "critiques",
      },
    ],
    idempotencyKey: input.idempotency_key,
  });
  const updated = await updateAttempt(serviceCtx, actor, {
    attemptId: created.attempt_id,
    readmeBody: `# Review: ${input.review_type}\n\nTarget: \`${target.attemptId}\`\n\n${input.body}\n`,
  });
  return jsonResult(
    trusted({
      review_attempt_id: created.attempt_id,
      branch: created.branch,
      target_attempt_id: target.attemptId,
      review_type: input.review_type,
      update: updated,
      next_steps:
        "Call submit_attempt on the review attempt to make it part of the " +
        "append-only record.",
    }),
  );
}

export async function toolReportAttempt(
  ctx: ToolContext,
  input: z.infer<typeof reportAttemptInput>,
) {
  const actor = requireAuth(ctx);
  requireScope(ctx, "inferfund:contribute");
  const serviceCtx = buildServiceContext(ctx);
  const result = await reportAttempt(serviceCtx, actor, {
    attemptId: input.attempt_id,
    reason: input.reason,
    details: input.details,
  });
  return jsonResult(
    trusted({
      ...result,
      note:
        "Moderators have been notified. Moderation is separate from " +
        "mathematical correctness; use review_attempt for correctness issues.",
    }),
  );
}
