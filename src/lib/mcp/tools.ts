export interface ToolContext {
  github: GitHubService;
  actor: Actor | null;
  scopes: string[];
  clientId: string | null;
}

export function buildServiceContext(toolCtx: ToolContext): ServiceContext {
  const config = getConfig();
  return {
    github: toolCtx.github,
    progressBranch: config.INFERFUND_PROGRESS_BRANCH,
    attemptBranchPrefix: config.INFERFUND_ATTEMPT_BRANCH_PREFIX,
    maxOpenAttempts: config.INFERFUND_MAX_OPEN_ATTEMPTS,
    maxAttemptsPerDay: config.INFERFUND_MAX_ATTEMPTS_PER_DAY,
    maxSubmissionsPerDay: config.INFERFUND_MAX_SUBMISSIONS_PER_DAY,
    maxLeanSubmissionsPerDay: config.INFERFUND_MAX_LEAN_SUBMISSIONS_PER_DAY,
    maxAttemptBytes: config.INFERFUND_MAX_ATTEMPT_BYTES,
    maxFilesPerAttempt: config.INFERFUND_MAX_FILES_PER_ATTEMPT,
    writesEnabled: config.writesEnabled,
    serviceCanWrite: config.serviceCanWrite,
  };
}

export function requireAuth(toolCtx: ToolContext): Actor {
  if (!toolCtx.actor) {
    throw new InferFundError(
      "AUTH_REQUIRED",
      "This tool requires an InferFund access token. Connect with an MCP " +
        "client and complete the GitHub authorization flow.",
    );
  }
  return toolCtx.actor;
}

export function requireScope(toolCtx: ToolContext, scope: string): void {
  if (!toolCtx.scopes.includes(scope)) {
    throw new InferFundError(
      "FORBIDDEN",
      `This operation requires the "${scope}" scope.`,
    );
  }
}

